#!/bin/bash
# GCP 훈련 환경 설정 예시
# 이 파일을 복사하여 config.sh로 저장하고 값을 수정하세요.
# cp config.example.sh config.sh

# =============================================================================
# GCP 프로젝트 설정
# =============================================================================

# GCP 프로젝트 ID (필수)
export GCP_PROJECT_ID="your-project-id"

# GCP Zone (선택사항, 기본값: us-central1-a)
export GCP_ZONE="us-central1-a"

# 인스턴스 이름 (선택사항, 기본값: ai-trader-training)
export INSTANCE_NAME="ai-trader-training"

# =============================================================================
# 인스턴스 사양 설정
# =============================================================================

# 머신 타입 (선택사항, 기본값: n1-standard-4)
# 옵션:
#   - n1-standard-4: 4 vCPU, 15GB RAM (~$0.19/시간)
#   - n1-standard-8: 8 vCPU, 30GB RAM (~$0.38/시간)
#   - n1-highmem-4: 4 vCPU, 26GB RAM (~$0.24/시간)
export MACHINE_TYPE="n1-standard-4"

# GPU 타입 (선택사항, 기본값: nvidia-tesla-t4)
# 옵션:
#   - nvidia-tesla-t4: 가성비 좋음 (~$0.35/시간)
#   - nvidia-tesla-v100: 고성능 (~$2.48/시간)
#   - nvidia-tesla-p4: 저가형 (~$0.60/시간)
#   - nvidia-tesla-k80: 구형, 저가 (~$0.45/시간)
export GPU_TYPE="nvidia-tesla-t4"

# GPU 개수 (선택사항, 기본값: 1)
export GPU_COUNT="1"

# 부트 디스크 크기 (선택사항, 기본값: 100GB)
export BOOT_DISK_SIZE="100GB"

# 부트 디스크 타입 (선택사항, 기본값: pd-standard)
# 옵션:
#   - pd-standard: 표준 HDD
#   - pd-ssd: SSD (더 빠르지만 비쌈)
export BOOT_DISK_TYPE="pd-standard"

# =============================================================================
# 데이터 설정
# =============================================================================

# 로컬 데이터베이스 경로 (필수)
# Windows 경로 예시: C:\Users\user\Workspace\datasets@20251005\datasets_norm_all.duckdb
# Linux/Mac 경로 예시: /home/user/datasets/datasets_norm_all.duckdb
export DB_PATH=""

# 데이터베이스 테이블명 (선택사항, 기본값: datasets)
export TABLE_NAME="datasets"

# =============================================================================
# 훈련 하이퍼파라미터
# =============================================================================

# 시퀀스 길이 (선택사항, 기본값: 60)
export SEQ_LEN="60"

# 임베딩 차원 (선택사항, 기본값: 128)
export EMBEDDING_DIM="128"

# 배치 크기 (선택사항, 기본값: 128)
# GPU 메모리에 따라 조정 필요
# T4 GPU: 128-256
# V100 GPU: 256-512
export BATCH_SIZE="128"

# 에포크 수 (선택사항, 기본값: 50)
export EPOCHS="50"

# 학습률 (선택사항, 기본값: 1e-4)
export LEARNING_RATE="1e-4"

# =============================================================================
# 비용 최적화 설정
# =============================================================================

# Preemptible VM 사용 여부 (선택사항, 기본값: false)
# true로 설정하면 최대 80% 비용 절감, 하지만 24시간 내 중단될 수 있음
export USE_PREEMPTIBLE="false"

# =============================================================================
# 사용 예시
# =============================================================================

# 1. 이 파일을 config.sh로 복사:
#    cp config.example.sh config.sh
#
# 2. config.sh를 편집하여 값 설정
#
# 3. 스크립트 실행 전에 설정 로드:
#    source config.sh
#    ./create_instance.sh
#
# 또는 한 번에:
#    source config.sh && ./create_instance.sh

# =============================================================================
# Zone별 가격 참고
# =============================================================================

# 미국 (저렴):
#   - us-central1-a, us-central1-b, us-central1-c
#   - us-east1-b, us-east1-c, us-east1-d
#
# 아시아 (한국과 가까움, 약간 비쌈):
#   - asia-northeast1-a (도쿄)
#   - asia-northeast3-a (서울)
#
# 유럽:
#   - europe-west1-b, europe-west1-c, europe-west1-d

# =============================================================================
# GPU 선택 가이드
# =============================================================================

# 개발/테스트:
#   - nvidia-tesla-t4 (가성비 최고)
#
# 프로덕션 훈련:
#   - nvidia-tesla-v100 (고성능)
#   - nvidia-tesla-p100 (중간 성능)
#
# 예산 제한:
#   - nvidia-tesla-k80 (구형이지만 저렴)
#   - nvidia-tesla-p4 (추론 최적화)

# =============================================================================
# 메모리 가이드
# =============================================================================

# 배치 크기와 GPU 메모리 관계:
#   T4 (16GB):
#     - Batch 128: 안전
#     - Batch 256: 가능
#     - Batch 512: 메모리 부족 가능성
#
#   V100 (16GB):
#     - Batch 256: 안전
#     - Batch 512: 가능
#     - Batch 1024: 메모리 부족 가능성
